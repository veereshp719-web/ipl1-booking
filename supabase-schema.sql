-- BlogSphere Supabase setup
-- Run this in Supabase Dashboard -> SQL Editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  username text unique not null,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, username)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', 'BlogSphere Writer'),
    coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1))
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  category text not null,
  author_id uuid not null references public.profiles(id) on delete cascade,
  image_url text,
  views integer not null default 0,
  likes integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.articles enable row level security;

drop policy if exists "Public profiles are readable" on public.profiles;
create policy "Public profiles are readable"
on public.profiles for select using (true);

drop policy if exists "Anyone can read published articles" on public.articles;
create policy "Anyone can read published articles"
on public.articles for select using (true);

drop policy if exists "Users can publish their own articles" on public.articles;
create policy "Users can publish their own articles"
on public.articles for insert to authenticated
with check (auth.uid() = author_id);

drop policy if exists "Users can update their own articles" on public.articles;
create policy "Users can update their own articles"
on public.articles for update to authenticated
using (auth.uid() = author_id)
with check (auth.uid() = author_id);

drop policy if exists "Users can delete their own articles" on public.articles;
create policy "Users can delete their own articles"
on public.articles for delete to authenticated
using (auth.uid() = author_id);
